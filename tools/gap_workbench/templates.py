#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""5线模板：按缺口类型给出五条独立推理角度（供推理者参考，不自动执行）"""
from __future__ import annotations
from typing import List, Tuple

# 五个基础角度
BASE_ANGLES = [
    ("线1", "结构", "从公式/链条内部推导目标：因子分解、化简、消去、量纲检查"),
    ("线2", "机制", "声称的机制是否成立：查该机制真正锁定的对象与数值（防机制错位）"),
    ("线3", "锚定", "实验/外部数据对照：标注来源、版本、数值与精度（实验输入锚定）"),
    ("线4", "跨文章", "检索其他文章的关联定义/归因/引用链（防幽灵引用）"),
    ("线5", "一致性", "链条数值审计：各环节自洽、单位一致、舍入与精度标注"),
]

# 按缺口类型特化的提示
TYPE_HINTS = {
    "NUMERIC": {
        "线1": "数值的因子分解：目标值 = 哪些已知几何常数/谱参数的组合",
        "线2": "数值的声称来源是否真实：声称的定理/公式是否真的给出该值",
        "线3": "与实验/物理常数对照（如玻尔半径、康普顿波长、PDG 值），标注版本",
        "线4": "全库检索：该量在哪些文章被定义/归因/使用，定义出处是否唯一",
        "线5": "数值链审计：每个中间量的来源与精度，舍入误差是否掩盖不一致",
    },
    "CLAIM": {
        "线1": "声称的推导链：从源头定理逐步重建，看能否走到声称结论",
        "线2": "机制错位检查：声称的机制（如根系结构）实际锁定的对象是什么",
        "线3": "实验/数据对照：声称的数值与实测/权威值的偏差（容差内？）",
        "线4": "跨文章一致性：其他文章对该声称的表述是否一致（含笔误/版本差异）",
        "线5": "引用链审计：声称的每个引用是否真实存在且指向正确内容",
    },
    "FORMULA": {
        "线1": "公式存在性：在库内全文检索该形式及等价形式（含变体写法）",
        "线2": "数学化简：从真实闭式出发，检验目标形式能否渐近/精确导出",
        "线3": "数值对照：目标形式代入已知实例 vs 实测/闭式值（数量级检验）",
        "线4": "邻近公式检查：同类闭式（如简并比例、失败率、系数）是否有类似结构",
        "线5": "结构对照：指数/因子结构（线性 vs 对数、多项式 vs 指数）是否与真实闭式同型",
    },
    "CONSISTENCY": {
        "线1": "链条内部：从首端到末端的每个中间量是否都有来源",
        "线2": "双值检查：同一量在不同文章/章节的取值是否一致（数值与标注）",
        "线3": "实验锚定：链条各环节与实验值的偏差（哪个环节贡献主要偏差）",
        "线4": "跨文章引用：链条引用的定理/文章是否存在、内容是否匹配",
        "线5": "舍入审计：四舍五入是否掩盖了不一致（保留有效数字重算）",
    },
}


def suggest_lines(gap_type: str = "NUMERIC") -> List[Tuple[str, str, str]]:
    """返回 5 条线的建议 [(线id, 假设名, 角度描述)]"""
    hints = TYPE_HINTS.get(gap_type, TYPE_HINTS["NUMERIC"])
    out = []
    for lid, name, base in BASE_ANGLES:
        out.append((lid, name, hints.get(lid, base)))
    return out
